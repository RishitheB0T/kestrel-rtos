"""Ahead-of-time code generation: quantized model -> C source.

Instead of shipping a model file plus an interpreter, we emit a C function
that calls the kernels in order with every shape, pointer and arena offset
fixed at compile time (like an AOT compiler / TensorRT "engine").
"""
import numpy as np

from memplan import Buffer, check, plan

HEADER = "/* Generated by tools/nn/compile_model.py - do not edit by hand. */\n"


def c_array(ctype, name, values, per_line=16, qualifiers="static const"):
    vals = [str(int(v)) for v in np.asarray(values).ravel()]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    body = ",\n    ".join(lines)
    return f"{qualifiers} {ctype} {name}[{len(vals)}] __attribute__((aligned(4))) = {{\n    {body}\n}};\n"


def padded_weights(q):
    w = q.w_q.reshape(q.out_c, q.col_len)
    out = np.zeros((q.out_c, q.col_stride), np.int8)
    out[:, :q.col_len] = w
    return out


def emit_conv(q):
    n = q.name
    s = c_array("int8_t", f"{n}_w", padded_weights(q))
    s += c_array("int32_t", f"{n}_bias", q.bias_folded, per_line=8)
    s += c_array("int32_t", f"{n}_mult", q.mult, per_line=8)
    s += c_array("int8_t", f"{n}_shift", q.shift)
    s += (f"static const nn_conv_t {n} = {{\n"
          f"    .in_h = {q.in_h}, .in_w = {q.in_w}, .in_c = {q.in_c}, .out_c = {q.out_c},\n"
          f"    .k = {q.k}, .pad = {q.pad}, .col_len = {q.col_len}, .col_stride = {q.col_stride},\n"
          f"    .in_zp = {q.in_zp}, .out_zp = {q.out_zp}, .act_min = {q.act_min}, .act_max = 127,\n"
          f"    .weights = {n}_w, .bias = {n}_bias, .mult = {n}_mult, .shift = {n}_shift,\n"
          f"}};\n\n")
    return s


def build_plan(qlayers):
    """The execution plan: ops in order, and the buffers they touch."""
    conv1, conv2, fc = qlayers
    ops = [
        ("conv", conv1, "input", "t_conv1"),
        ("pool", (8, 8, 16), "t_conv1", "t_pool1"),
        ("conv", conv2, "t_pool1", "t_conv2"),
        ("pool", (4, 4, 32), "t_conv2", "t_pool2"),
        ("conv", fc, "t_pool2", "logits"),
    ]
    buffers = [
        Buffer("t_conv1", 8 * 8 * 16, 0, 1),
        Buffer("t_pool1", 4 * 4 * 16, 1, 2),
        Buffer("t_conv2", 4 * 4 * 32, 2, 3),
        Buffer("t_pool2", 2 * 2 * 32, 3, 4),
    ]
    for i, (kind, q, _, _) in enumerate(ops):
        if kind == "conv":  # im2col scratch: 2 rows of int16, alive for one op
            buffers.append(Buffer(f"scratch_{q.name}", 2 * q.col_stride * 2, i, i))
    arena = plan(buffers)
    check(buffers)
    return ops, buffers, arena


def generate_model(qlayers, path_c, path_h):
    ops, buffers, arena = build_plan(qlayers)
    off = {b.name: b.offset for b in buffers}
    macs = sum(q.macs for q in qlayers)

    def ref(name):
        return name if name in ("input", "logits") else f"arena + {off[name]}"

    body = []
    for i, (kind, q, src, dst) in enumerate(ops):
        if kind == "conv":
            body.append(f"    /* op {i}: {q.name}  {q.in_h}x{q.in_w}x{q.in_c} -> "
                        f"{q.in_h}x{q.in_w}x{q.out_c}{' + ReLU' if q.relu else ''} */\n"
                        f"    nn_conv2d(&{q.name}, {ref(src)}, {ref(dst)}, "
                        f"(int16_t *)(arena + {off['scratch_' + q.name]}), impl);\n")
        else:
            h, w, c = q
            body.append(f"    /* op {i}: maxpool 2x2  {h}x{w}x{c} -> {h // 2}x{w // 2}x{c} */\n"
                        f"    nn_maxpool2x2({ref(src)}, {ref(dst)}, {h}, {w}, {c});\n")

    layout = "\n".join(f" *   {b.name:<16} {b.size:5d} B  at offset {b.offset:5d}  "
                       f"(alive ops {b.first_op}-{b.last_op})" for b in sorted(buffers, key=lambda b: b.offset))
    with open(path_h, "w") as f:
        f.write(HEADER + "#ifndef MODEL_GEN_H\n#define MODEL_GEN_H\n\n#include \"nn.h\"\n\n"
                f"#define MODEL_INPUT_BYTES  {qlayers[0].in_h * qlayers[0].in_w * qlayers[0].in_c}\n"
                f"#define MODEL_NUM_CLASSES  {qlayers[-1].out_c}\n"
                f"#define MODEL_MACS         {macs}u\n"
                f"#define MODEL_ARENA_BYTES  {arena}\n\n"
                "void model_run(const int8_t *input, int8_t *logits, nn_impl_t impl);\n\n"
                "extern const int model_test_count;\n"
                "extern const int8_t model_test_images[][MODEL_INPUT_BYTES];\n"
                "extern const uint8_t model_test_labels[];\n"
                "extern const int8_t model_test_logits[][MODEL_NUM_CLASSES];\n"
                "\n#endif\n")
    with open(path_c, "w") as f:
        f.write(HEADER + "#include \"model_gen.h\"\n\n")
        for q in qlayers:
            f.write(emit_conv(q))
        f.write(f"/* Arena layout chosen by tools/nn/memplan.py:\n{layout}\n */\n"
                f"static int8_t arena[MODEL_ARENA_BYTES] __attribute__((aligned(4)));\n\n"
                "void model_run(const int8_t *input, int8_t *logits, nn_impl_t impl)\n{\n"
                + "".join(body) + "}\n")
    return ops, buffers, arena


def generate_testset(images_q, labels, golden, path_c):
    n = len(images_q)
    with open(path_c, "w") as f:
        f.write(HEADER + "#include \"model_gen.h\"\n\n")
        f.write(f"const int model_test_count = {n};\n\n")
        f.write(f"const int8_t model_test_images[{n}][MODEL_INPUT_BYTES] = {{\n")
        for img in images_q.reshape(n, -1):
            f.write("    {" + ", ".join(str(int(v)) for v in img) + "},\n")
        f.write("};\n\n")
        f.write(c_array("uint8_t", "model_test_labels", labels, per_line=32, qualifiers="const"))
        f.write(f"\nconst int8_t model_test_logits[{n}][MODEL_NUM_CLASSES] = {{\n")
        for row in golden:
            f.write("    {" + ", ".join(str(int(v)) for v in row) + "},\n")
        f.write("};\n")
