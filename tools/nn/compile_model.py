#!/usr/bin/env python3
"""Model compiler: train -> quantize -> verify -> plan memory -> emit C.

    python3 tools/nn/compile_model.py            # reuse saved float weights
    python3 tools/nn/compile_model.py --retrain  # train from scratch first

Outputs nn/model_gen.{c,h}, nn/testset_gen.c and nn/MODEL_REPORT.md.
"""
import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)

from codegen import generate_model, generate_testset  # noqa: E402
from intref import run_int  # noqa: E402
from layers import Net  # noqa: E402
from quantize import quantize_input, quantize_net  # noqa: E402
from train import accuracy, load_digits_split, train  # noqa: E402

WEIGHTS = os.path.join(HERE, "model_float.npz")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--retrain", action="store_true", help="train the float model again")
    ap.add_argument("--epochs", type=int, default=40)
    args = ap.parse_args()

    x_tr, y_tr, x_te, y_te = load_digits_split()
    print(f"dataset: {len(x_tr)} train / {len(x_te)} test images (8x8 handwritten digits)")

    net = Net(np.random.default_rng(0))
    if args.retrain or not os.path.exists(WEIGHTS):
        print("training float model...")
        net = train(x_tr, y_tr, epochs=args.epochs)
        np.savez(WEIGHTS, **net.state())
    else:
        net.load(np.load(WEIGHTS))
    acc_float = accuracy(net, x_te, y_te)

    qlayers = quantize_net(net, x_tr)  # calibrate on training data only
    x_te_q = quantize_input(x_te)
    golden = run_int(qlayers, x_te_q)
    pred_int = golden.argmax(axis=1)
    acc_int = float((pred_int == y_te).mean())
    agree = float((pred_int == net.forward(x_te).argmax(axis=1)).mean())

    nn_dir = os.path.join(ROOT, "nn")
    _, buffers, arena = generate_model(qlayers, os.path.join(nn_dir, "model_gen.c"),
                                       os.path.join(nn_dir, "model_gen.h"))
    generate_testset(x_te_q, y_te, golden, os.path.join(nn_dir, "testset_gen.c"))

    params = sum(q.w_q.size + q.out_c for q in qlayers)
    weight_bytes = sum(q.out_c * q.col_stride + 9 * q.out_c for q in qlayers)
    macs = sum(q.macs for q in qlayers)
    naive_ram = sum(b.size for b in buffers)
    report = [
        "# Model report (generated by tools/nn/compile_model.py)",
        "",
        "| | |",
        "|---|---|",
        f"| Architecture | conv3x3(16)+ReLU, maxpool, conv3x3(32)+ReLU, maxpool, fc(10) |",
        f"| Parameters | {params} |",
        f"| Multiply-accumulates per inference | {macs} |",
        f"| Float32 test accuracy | {acc_float * 100:.2f}% |",
        f"| Int8 test accuracy | {acc_int * 100:.2f}% |",
        f"| Int8 vs float agreement | {agree * 100:.2f}% of predictions identical |",
        f"| Weights in flash (int8 + int32 bias/requant) | {weight_bytes} B (float32 would be {params * 4} B) |",
        f"| Activation arena (planned) | {arena} B |",
        f"| Activation memory without planning | {naive_ram} B |",
        "",
        "Arena layout:",
        "",
        "```",
    ] + [f"{b.name:<16} {b.size:5d} B @ {b.offset:5d}   alive ops {b.first_op}-{b.last_op}"
         for b in sorted(buffers, key=lambda b: b.offset)] + ["```", ""]
    with open(os.path.join(nn_dir, "MODEL_REPORT.md"), "w") as f:
        f.write("\n".join(report))
    print("\n".join(report[4:13]))


if __name__ == "__main__":
    main()
